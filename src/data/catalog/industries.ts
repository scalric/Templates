import type { CategoryId, Template } from '../../types/template'
import type { IconName } from '../../types/icons'
import type { SiteTheme } from '../../types/site'
import { cta, defineTemplate, features, footer, hero, navbar, showcase, testimonials } from '../builders'

/** Everything a business-specific template says, in one place. */
interface Spec {
  slug: string
  name: string
  tagline: string
  description: string
  category: CategoryId
  tags: string[]
  popularity: number
  premium?: boolean
  icon: IconName
  theme: {
    primary: string
    secondary: string
    background?: string
    text?: string
    radius: SiteTheme['radius']
    headingFont: SiteTheme['headingFont']
  }
  nav: string[]
  hero: { eyebrow: string; title: string; subtitle: string; primaryCta: string; secondaryCta: string }
  services: { icon: IconName; title: string; description: string }[]
  reasons: { icon: IconName; title: string; description: string }[]
  reviews: { quote: string; name: string; role: string }[]
  cta: { title: string; subtitle: string; button: string }
  contact: { address: string; phone: string; email: string }
}

const CREATED_AT = '2026-10-28'

/** Builds the standard one-page business site from a spec. Every template uses the same structure. */
function fromSpec(spec: Spec): Template {
  const { theme, contact } = spec
  return defineTemplate({
    slug: spec.slug,
    name: spec.name,
    tagline: spec.tagline,
    description: spec.description,
    category: spec.category,
    tags: spec.tags,
    price: spec.premium ? 'premium' : 'free',
    popularity: spec.popularity,
    createdAt: CREATED_AT,
    author: 'Templates Studio',
    highlights: spec.reasons.map((r) => r.title),
    includedPages: ['Home', ...spec.nav.slice(1, 4)],
    theme: {
      primary: theme.primary,
      primaryText: '#ffffff',
      secondary: theme.secondary,
      background: theme.background ?? '#ffffff',
      text: theme.text ?? '#16161d',
      muted: '#64748b',
      radius: theme.radius,
      headingFont: theme.headingFont,
    },
    sections: [
      navbar({ brand: spec.name, icon: spec.icon, links: spec.nav, cta: spec.hero.primaryCta }),
      hero({
        layout: 'split',
        eyebrow: spec.hero.eyebrow,
        title: spec.hero.title,
        subtitle: spec.hero.subtitle,
        primaryCta: spec.hero.primaryCta,
        secondaryCta: spec.hero.secondaryCta,
        imageLabel: spec.name,
        imageIcon: spec.icon,
      }),
      showcase({ title: 'What we offer', subtitle: spec.tagline, variant: 'cards', items: spec.services }),
      features({ title: 'Why choose us', items: spec.reasons }),
      testimonials({ title: 'What clients say', items: spec.reviews }),
      cta({ title: spec.cta.title, subtitle: spec.cta.subtitle, button: spec.cta.button, tone: 'primary' }),
      footer({
        brand: spec.name,
        tagline: spec.tagline,
        columns: [
          { title: 'Quick links', links: spec.nav },
          { title: 'Services', links: spec.services.map((s) => s.title) },
          {
            title: 'Contact',
            links: [],
            details: [
              { icon: 'map-pin', text: contact.address },
              { icon: 'phone', text: contact.phone },
              { icon: 'mail', text: contact.email },
            ],
          },
        ],
        copyright: `© 2026 ${spec.name}. All rights reserved.`,
      }),
    ],
  })
}

